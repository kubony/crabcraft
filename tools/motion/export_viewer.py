"""Export a light Jumper model for the motion dev harness (dev/motion.html).

    .venv/bin/python tools/motion/export_viewer.py      (uv venv with mujoco + fast-simplification)

The body tree, joint axes and visual meshes come from the *compiled* MuJoCo model the clips were
recorded with, so forward kinematics in the browser can be compared one to one with MuJoCo.
Meshes are decimated (fast-simplification) to keep the harness light. This is a stand-in until
src/crab's real model is merged; it is not used by the game.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import mujoco
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from jumper_sim import load_model  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "dev" / "assets" / "motion-viewer"


def main(keep: float = 0.22, min_faces: int = 200) -> None:
    import fast_simplification

    m = load_model(render=True)
    OUT.mkdir(parents=True, exist_ok=True)
    pos_chunks, idx_chunks, meshes, mesh_index = [], [], [], {}
    voff = ioff = 0
    bodies = []
    total_in = total_out = 0
    for b in range(1, m.nbody):
        jnt = None
        if m.body_jntnum[b]:
            j = m.body_jntadr[b]
            if m.jnt_type[j] == mujoco.mjtJoint.mjJNT_HINGE:
                jnt = {"name": mujoco.mj_id2name(m, mujoco.mjtObj.mjOBJ_JOINT, j),
                       "axis": [round(float(x), 7) for x in m.jnt_axis[j]],
                       "pos": [round(float(x), 7) for x in m.jnt_pos[j]]}
        geoms = []
        for g in range(m.body_geomadr[b], m.body_geomadr[b] + m.body_geomnum[b]):
            if m.geom_type[g] != mujoco.mjtGeom.mjGEOM_MESH or m.geom_group[g] != 2:
                continue
            mid = int(m.geom_dataid[g])
            if mid not in mesh_index:
                va, vn = m.mesh_vertadr[mid], m.mesh_vertnum[mid]
                fa, fn = m.mesh_faceadr[mid], m.mesh_facenum[mid]
                verts = m.mesh_vert[va:va + vn].astype(np.float64)
                faces = m.mesh_face[fa:fa + fn].astype(np.int64)
                total_in += fn
                if fn > min_faces:
                    target = max(min_faces / fn, keep)
                    v2, f2 = fast_simplification.simplify(verts, faces, target_reduction=1.0 - target)
                else:
                    v2, f2 = verts, faces
                total_out += len(f2)
                mesh_index[mid] = len(meshes)
                meshes.append({"name": mujoco.mj_id2name(m, mujoco.mjtObj.mjOBJ_MESH, mid),
                               "vertOffset": voff, "vertCount": int(len(v2)),
                               "indexOffset": ioff, "indexCount": int(f2.size)})
                pos_chunks.append(v2.astype("<f4").ravel())
                idx_chunks.append(f2.astype("<u4").ravel())
                voff += len(v2)
                ioff += f2.size
            geoms.append({"mesh": mesh_index[mid],
                          "pos": [round(float(x), 7) for x in m.geom_pos[g]],
                          "quat": [round(float(x), 7) for x in m.geom_quat[g]],
                          "rgba": [round(float(x), 4) for x in m.geom_rgba[g]]})
        bodies.append({"name": mujoco.mj_id2name(m, mujoco.mjtObj.mjOBJ_BODY, b),
                       "parent": int(m.body_parentid[b]) - 1,
                       "pos": [round(float(x), 7) for x in m.body_pos[b]],
                       "quat": [round(float(x), 7) for x in m.body_quat[b]],
                       "joint": jnt, "geoms": geoms})
    positions = np.concatenate(pos_chunks)
    indices = np.concatenate(idx_chunks)
    (OUT / "jumper-lite.bin").write_bytes(positions.tobytes() + indices.tobytes())
    meta = {
        "note": "Jumper (KingKongRobotics/jumper, Apache-2.0) visual meshes, decimated, in MuJoCo body frames "
                "(Z-up, X forward). Generated by tools/motion/export_viewer.py.",
        "frame": "mujoco",
        "positionCount": int(positions.size),
        "indexCount": int(indices.size),
        "bodies": bodies,
        "meshes": meshes,
    }
    (OUT / "jumper-lite.json").write_text(json.dumps(meta, separators=(",", ":")))
    print(f"faces {total_in} -> {total_out}, {len(meshes)} meshes, {len(bodies)} bodies, "
          f"{(OUT / 'jumper-lite.bin').stat().st_size / 1e6:.2f} MB")


if __name__ == "__main__":
    main()
